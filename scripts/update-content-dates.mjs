// Regenerates src/content/contentDates.ts from git history.
//
//   node scripts/update-content-dates.mjs
//
// Run it before a release (after committing content changes). It records, per public page, the date its
// source files last changed, and per case-study video the date the file was first added. The result is
// committed so production builds do not depend on git history being available. Files with uncommitted
// changes are stamped with today's date.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const git = (args) => execFileSync("git", args, { encoding: "utf8" }).trim();
const today = new Date().toISOString().slice(0, 10);

function lastChanged(paths) {
  const existing = paths.filter((p) => fs.existsSync(p));
  if (!existing.length) throw new Error("none of these exist: " + paths.join(", "));
  if (git(["status", "--porcelain", "--", ...existing])) return today;
  return git(["log", "-1", "--format=%cs", "--", ...existing]) || today;
}
function firstAdded(file) {
  if (git(["status", "--porcelain", "--", file]).startsWith("??")) return today;
  const out = git(["log", "--diff-filter=A", "--format=%cs", "--", file]).split("\n").filter(Boolean);
  return out[out.length - 1] || today;
}

const slugsIn = (dir) => fs.readdirSync(dir).filter((f) => f.endsWith(".ts") && f !== "index.ts" && f !== "types.ts" && f !== "shared.ts" && f !== "faqs.ts").map((f) => f.slice(0, -3));

const pages = {
  "/": ["src/components/home", "src/content/home.ts", "src/content/stats.ts", "src/content/siteFaqs.ts", "src/content/serviceOfferings.ts", "src/app/(site)/page.tsx", "src/app/layout.tsx"],
  "/about": ["src/components/about", "src/content/about.ts", "src/content/offices.ts", "src/content/stats.ts", "src/content/siteFaqs.ts", "src/app/(site)/about"],
  "/services": ["src/components/services/ServicesPage.tsx", "src/content/servicesPage.ts", "src/content/serviceOfferings.ts", "src/app/(site)/services/page.tsx"],
  "/work": ["src/components/work/WorkPage.tsx", "src/components/work/WorkCaseBrowser.tsx", "src/content/workPage.ts", "src/app/(site)/work/page.tsx"],
  "/careers": ["src/components/careers", "src/content/careers.ts", "src/app/(site)/careers/page.tsx"],
  "/awards": ["src/components/awards", "src/content/awards.ts", "src/app/(site)/awards"],
  "/contact": ["src/components/contact", "src/content/contact.ts", "src/content/offices.ts", "src/app/(site)/contact"],
  "/privacy-policy": ["src/content/legal.ts", "src/components/legal", "src/app/(site)/privacy-policy"],
};
for (const slug of slugsIn("src/content/servicePages")) {
  // faqs.ts is shared, so an FAQ edit moves every service page's date — an over-estimate, never an under-estimate.
  pages[`/services/${slug}`] = [`src/content/servicePages/${slug}.ts`, "src/content/servicePages/faqs.ts"];
}
for (const slug of slugsIn("src/content/caseStudies")) {
  pages[`/work/${slug}`] = [`src/content/caseStudies/${slug}.ts`];
}

const pageLastModified = Object.fromEntries(Object.entries(pages).map(([p, files]) => [p, lastChanged(files)]));

const videoUploadDates = {};
const videoRoot = "public/videos";
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]));
for (const file of walk(videoRoot)) {
  if (!/\.(mp4|webm|mov)$/i.test(file)) continue;
  videoUploadDates["/" + file.split(path.sep).slice(1).join("/")] = firstAdded(file);
}

const body = (obj) => Object.entries(obj).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
fs.writeFileSync(
  "src/content/contentDates.ts",
  `// GENERATED by scripts/update-content-dates.mjs — do not edit by hand. Regenerate before each release.
// Dates come from git history (last commit touching a page's source files). They feed the sitemap
// <lastmod>, Article dateModified and VideoObject uploadDate.

export const contentDatesGeneratedOn = ${JSON.stringify(today)};

/** Public path -> date (YYYY-MM-DD) the page's source content last changed. */
export const pageLastModified: Record<string, string> = {
${body(pageLastModified)}
};

/** Video file path under /public -> date (YYYY-MM-DD) the file was first added to the site. */
export const videoUploadDates: Record<string, string> = {
${body(videoUploadDates)}
};
`,
);
console.log(`pages: ${Object.keys(pageLastModified).length}, videos: ${Object.keys(videoUploadDates).length}, generated ${today}`);
